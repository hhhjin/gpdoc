use gpui_icons::LucideIcon;

#[wasm_bindgen::prelude::wasm_bindgen]
pub fn toolbar_icon(command: &str) -> String {
    let icon = match command {
        "acceptMention" => LucideIcon::AtSign,
        "addColumnAfter" => LucideIcon::BetweenVerticalEnd,
        "addRowAfter" => LucideIcon::BetweenHorizontalEnd,
        "duplicate" => LucideIcon::CopyPlus,
        "exportMarkdown" => LucideIcon::FileOutput,
        "find" => LucideIcon::Search,
        "goToNextResult" => LucideIcon::ChevronDown,
        "findSuggestion" => LucideIcon::MessageCircle,
        "insertInlineMath" => LucideIcon::Sigma,
        "insertTable" => LucideIcon::Table,
        "liftListItem" => LucideIcon::ListIndentDecrease,
        "listBackspace" => LucideIcon::Delete,
        "setAudio" => LucideIcon::AudioLines,
        "setCodeBlock" => LucideIcon::SquareCode,
        "setHardBreak" => LucideIcon::CornerDownLeft,
        "toggleHighlight" => LucideIcon::Highlighter,
        "setHorizontalRule" => LucideIcon::Minus,
        "setImage" => LucideIcon::Image,
        "setLink" => LucideIcon::Link,
        "setMarkdown" => LucideIcon::FileInput,
        "setParagraph" => LucideIcon::Pilcrow,
        "setRubyText" => LucideIcon::Languages,
        "sinkListItem" => LucideIcon::ListIndentIncrease,
        "splitListItem" => LucideIcon::ListEnd,
        "styleSelection" => LucideIcon::Palette,
        "toggleBlockquote" => LucideIcon::TextQuote,
        "toggleBold" => LucideIcon::Bold,
        "toggleBulletList" => LucideIcon::List,
        "toggleCode" => LucideIcon::Code,
        "toggleItalic" => LucideIcon::Italic,
        "toggleOrderedList" => LucideIcon::ListOrdered,
        "toggleStrike" => LucideIcon::Strikethrough,
        "toggleSubscript" => LucideIcon::Subscript,
        "toggleSuperscript" => LucideIcon::Superscript,
        "toggleTaskList" => LucideIcon::ListChecks,
        "toggleUnderline" => LucideIcon::Underline,
        "unsetDetails" => LucideIcon::UnfoldVertical,
        "wrapDetails" => LucideIcon::ListCollapse,
        "heading-1" => LucideIcon::Heading1,
        "heading-2" => LucideIcon::Heading2,
        "heading-3" => LucideIcon::Heading3,
        "align-left" => LucideIcon::TextAlignStart,
        "align-center" => LucideIcon::TextAlignCenter,
        "align-right" => LucideIcon::TextAlignEnd,
        "align-justify" => LucideIcon::TextAlignJustify,
        "unsetLink" => LucideIcon::Unlink,
        "unsetRubyText" => LucideIcon::RemoveFormatting,
        "replaceMatches" => LucideIcon::ReplaceAll,
        _ => LucideIcon::MousePointerClick,
    };
    std::str::from_utf8(icon.svg_bytes())
        .expect("Lucide SVG is UTF-8")
        .to_owned()
}
